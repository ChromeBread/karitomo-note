// en: the GU mode, which uses the English bodies in js/spec-en.js (passed in as topicsEn)
export function renderSpec(topic, { D, esc, en = false, topicsEn = null }) {
  const link = (hash, label) => `<a href="#${hash}">${esc(label)}</a>`;
  const skill = (name) => {
    const t = D.treeByName[name];
    return t ? `<div class="card"><b>${esc(t.name)}</b>${t.effects.map((e) => `<div><span class="${e.pts > 0 ? "" : "hi"}">${esc(e.name)}（${e.pts > 0 ? "+" : ""}${e.pts}）</span> <span class="muted">${esc(e.desc)}</span>${D.skillDetails?.[e.name] ? `<div class="detail">${esc(D.skillDetails[e.name])}</div>` : ""}</div>`).join("")}</div>` : "";
  };
  const t = (en && topicsEn?.[topic]) || TOPICS[topic];
  if (!t) return null;
  return { title: t.title, html: t.body({ link, skill, D, esc }) };
}
